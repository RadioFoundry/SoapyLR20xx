# Regenerate lr20xx-sys/src/bindings.rs (and bindings_linux.rs, the Linux HAL's) from the C headers with bindgen.
# A development step: the output is committed, so users build without libclang. Needs bindgen-cli
# (cargo install bindgen-cli) and libclang. Run after a header changes.
set -euf # -f: the regexes below aren't globs
here=$(cd "$(dirname "$0")/.." && pwd)
inc=$here/../lib/include
pinc=$here/../proto/include
out=$here/lr20xx-sys/src
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
cat >"$tmp/all.h" <<H
#include "lr20xx.h"
#include "lr20xx_hal.h"
#include "lr20xx_port.h"
#include "lr20xx_iq.h"
#include "lr20xx_board.h"
#include "lr20xx_chips.h"
#include "lr20xx_tx.h"
#include "lr20xx_cmd.h"
#include "lr20xx_radio.h"
#include "lr20xx_lora.h"
#include "lr20xx_fsk.h"
#include "lr20xx_proto.h"
#include "lr20xx_link.h"
H
printf '#include "lr20xx_hal_linux.h"\n' >"$tmp/linux.h"
hdr='// SPDX-License-Identifier: MIT
// SPDX-FileCopyrightText: 2026 Spencer Fowler
// Generated by rust/tools/gen-bindings.sh from lib/include and proto/include: do not edit.
'
common="--allowlist-function (lr20xx|LR20XX)_.* --allowlist-type (lr20xx|LR20XX)_.* --allowlist-var (lr20xx|LR20XX)_.*
 --no-layout-tests --use-core --default-enum-style consts --no-prepend-enum-name --no-doc-comments --merge-extern-blocks --sort-semantically"
# shellcheck disable=SC2086
bindgen "$tmp/all.h" $common -- -I"$inc" -I"$pinc" -std=c11 >"$tmp/b.rs"
# shellcheck disable=SC2086
bindgen "$tmp/linux.h" --allowlist-function lr20xx_hal_linux_open --allowlist-type lr20xx_linux_cfg_t \
    --blocklist-type lr20xx_hal_t --blocklist-type lr20xx_err_t --no-layout-tests --use-core --no-doc-comments \
    -- -I"$inc" -std=c11 >"$tmp/l.rs"
{ printf '%s' "$hdr"; cat "$tmp/b.rs"; } >"$out/bindings.rs"
{ printf '%s' "$hdr"; cat "$tmp/l.rs"; } >"$out/bindings_linux.rs"
rustfmt --edition 2021 --config-path "$here/rustfmt.toml" "$out/bindings.rs" "$out/bindings_linux.rs"
echo "wrote $out/bindings.rs, $out/bindings_linux.rs"
